import pandas as pd
import numpy as np
import tensorflow as tf
from tensorflow.keras.preprocessing.image import ImageDataGenerator
from tensorflow.keras import layers, models, optimizers
import os

# --- CONFIGURATION ---
# 1. Path to your CSV file
csv_path = 'train.csv'

# 2. Path to the FOLDER containing the 'train' folder
# This matches the folder structure you showed in your screenshots
base_img_path = '/content/real_vs_fake/real-vs-fake/'

print(f"Checking for images in: {base_img_path}")

# --- DATA LOADING ---
# Load the CSV metadata
try:
    df = pd.read_csv(csv_path)
    print(f"Successfully loaded CSV with {len(df)} rows.")
except FileNotFoundError:
    print(f"ERROR: Could not find {csv_path}. Please make sure you uploaded it.")

# Check the first few rows to confirm column names
# We expect 'path' (relative path) and 'label' (0/1) or 'label_str' ('real'/'fake')
print("First 5 rows of data:")
print(df.head())

# --- GENERATOR SETUP (The RAM Saver) ---
# This creates a "stream" that loads images on-the-fly
train_datagen = ImageDataGenerator(
    rescale=1./255,        # Normalize pixel values (0-255 -> 0-1)
    validation_split=0.2   # Reserve 20% of data for validation
)

print("\n--- Setting up Training Stream ---")
train_generator = train_datagen.flow_from_dataframe(
    dataframe=df,
    directory=base_img_path,   # Folder where images are stored
    x_col='path',              # Column with "train/real/0000.jpg"
    y_col='label_str',         # Column with "real" or "fake" strings
    target_size=(256, 256),    # Resize images to 256x256
    batch_size=32,             # Load 32 images at a time (Low RAM usage)
    class_mode='binary',       # Real vs Fake
    subset='training',         # This is the Training set
    shuffle=True
)

print("\n--- Setting up Validation Stream ---")
val_generator = train_datagen.flow_from_dataframe(
    dataframe=df,
    directory=base_img_path,
    x_col='path',
    y_col='label_str',
    target_size=(256, 256),
    batch_size=32,
    class_mode='binary',
    subset='validation',       # This is the Validation set
    shuffle=False
)

# --- MODEL ARCHITECTURE ---
model = models.Sequential([
    # Input Layer
    layers.Input(shape=(256, 256, 3)),

    # Convolution Block 1
    layers.Conv2D(32, (3, 3), activation='relu'),
    layers.MaxPooling2D((2, 2)),

    # Convolution Block 2
    layers.Conv2D(64, (3, 3), activation='relu'),
    layers.MaxPooling2D((2, 2)),

    # Convolution Block 3
    layers.Conv2D(128, (3, 3), activation='relu'),
    layers.MaxPooling2D((2, 2)),

    # Classification Head
    layers.Flatten(),
    layers.Dense(128, activation='relu'),
    layers.Dropout(0.5),                # Helps prevent overfitting
    layers.Dense(1, activation='sigmoid') # Output: 0-1 probability
])

# Compile
model.compile(optimizer='adam',
              loss='binary_crossentropy',
              metrics=['accuracy'])

print("Model compiled successfully!")
model.summary()

# --- TRAINING ---
print("Starting training...")
history = model.fit(
    train_generator,
    validation_data=val_generator,
    epochs=5  # You can increase this to 10 or 20 later
)

print("Training complete.")

