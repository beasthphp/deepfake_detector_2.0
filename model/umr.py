def extract_features(fr):
  feat=[]
  lab=[]
  for index,row in fr.iterrows():
    try:
      ip = row['full_path']
      with Image.open(ip) as img:
        img = img.convert('L').resize((64,64))
        img_array = np.array(img)
        f = np.fft.fft2(img_array)
        fshift = np.fft.fftshift(f)
        magnitude_spectrum = 20 * np.log(np.abs(fshift) + 1e-9)
        mean_freq = np.mean(magnitude_spectrum)
        std_freq = np.std(magnitude_spectrum)
        mean_pixel = np.mean(img_array)
        feat.append([mean_freq, std_freq, mean_pixel])
        lab.append(row['label'])
    except Exception as e:
      pass
  return np.array(feat), np.array(lab)
